const (
	manifestFilename = "checkpoint.sha256.json"
	baselineCommit   = "c11a1b0fbe02de266ba11963abedd0d07f427be9"
)

var caseNames = []string{
	"allowed-action",
	"denied-action",
	"adapter-bypass",
	"no-policy-loaded",
	"unknown-outcome",
}

type manifest struct {
	SchemaVersion  string  `json:"schemaVersion"`
	BaselineCommit string  `json:"baselineCommit"`
	Entries        []entry `json:"entries"`
}

type entry struct {
	Kind   string `json:"kind"`
	Name   string `json:"name"`
	SHA256 string `json:"sha256"`
}

func main() {
	if err := run(os.Args[1:], os.Stdout, os.Stderr); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return
		}
		fatal(err)
	}
}

func run(args []string, stdout, stderr io.Writer) error {
	flags := flag.NewFlagSet("checkpoint", flag.ContinueOnError)
	flags.SetOutput(stderr)
	root := flags.String("root", "", "path to the agent-governance directory")
	writeManifest := flags.Bool("write", false, "write the manifest under root instead of printing it")
	verifyManifest := flags.Bool("verify", false, "compare generated bytes with the committed manifest")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected positional arguments: %v", flags.Args())
	}
	if *root == "" {
		return errors.New("-root is required")
	}
	if *writeManifest && *verifyManifest {
		return errors.New("-write and -verify are mutually exclusive")
	}

	data, err := buildManifest(*root)
	if err != nil {
		return err
	}
	path := filepath.Join(*root, manifestFilename)
	switch {
	case *writeManifest:
		err = os.WriteFile(path, data, 0o644)
	case *verifyManifest:
		var want []byte
		want, err = os.ReadFile(path)
		if err == nil && !bytes.Equal(data, want) {
			err = fmt.Errorf("%s does not match generated checkpoint", path)
		}
	default:
		_, err = stdout.Write(data)
	}
	return err
}

func buildManifest(root string) ([]byte, error) {
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return nil, fmt.Errorf("resolve root: %w", err)
	}

	entries := make([]entry, 0, 64)
	for _, producer := range []string{"agt", "non-agt"} {
		for _, caseName := range caseNames {
			evidencePath := filepath.Join(absRoot, "fixtures", "evidence", producer, caseName+".json")
			built, err := demokit.BuildCase(evidencePath)
			if err != nil {
				return nil, fmt.Errorf("build %s/%s: %w", producer, caseName, err)
			}
			name := producer + "/" + caseName + ".json"
			entries = append(entries,
				entry{Kind: "predicate-body", Name: name, SHA256: hashBytes(built.PredicateBody)},
				entry{Kind: "test-result-statement", Name: name, SHA256: hashBytes(built.TestResultStatement)},
			)
		}
	}

	policyDigest, err := calculatePolicyDirectoryDigest(filepath.Join(absRoot, "policy"))
	if err != nil {
		return nil, err
	}
	entries = append(entries, entry{
		Kind:   "policy-bundle",
		Name:   "policy",
		SHA256: policyDigest,
	})

	frozen, err := frozenInputPaths(absRoot)
	if err != nil {
		return nil, err
	}
	for _, rel := range frozen {
		data, err := os.ReadFile(filepath.Join(absRoot, filepath.FromSlash(rel)))
		if err != nil {
			return nil, fmt.Errorf("read frozen input %s: %w", rel, err)
		}
		entries = append(entries, entry{Kind: "frozen-input", Name: rel, SHA256: hashBytes(data)})
	}

	sort.Slice(entries, func(i, j int) bool {
		if entries[i].Kind != entries[j].Kind {
			return entries[i].Kind < entries[j].Kind
		}
		return entries[i].Name < entries[j].Name
	})

	output, err := json.MarshalIndent(manifest{
		SchemaVersion:  "1",
		BaselineCommit: baselineCommit,
		Entries:        entries,
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal manifest: %w", err)
	}
	return append(output, '\n'), nil
}

func frozenInputPaths(root string) ([]string, error) {
	for _, rel := range frozenInputs {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(rel))); err != nil {
			return nil, fmt.Errorf("resolve frozen input %s: %w", rel, err)
		}
	}
	return append([]string(nil), frozenInputs...), nil
}

