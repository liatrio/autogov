// calculatePolicyDirectoryDigest intentionally mirrors AutoGov's public policy
// digest contract: lexically walk the directory, hashing each selected relative
// path followed immediately by its file bytes.
func calculatePolicyDirectoryDigest(dir string) (string, error) {
	h := sha256.New()
	err := filepath.Walk(dir, func(path string, info os.FileInfo, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if info.IsDir() {
			return nil
		}
		if ext := filepath.Ext(path); ext != ".rego" && ext != ".json" && ext != ".yaml" {
			return nil
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		if _, err := io.WriteString(h, filepath.ToSlash(rel)); err != nil {
			return err
		}
		file, err := os.Open(path)
		if err != nil {
			return err
		}
		_, copyErr := io.Copy(h, file)
		closeErr := file.Close()
		return errors.Join(copyErr, closeErr)
	})
	if err != nil {
		return "", fmt.Errorf("calculate policy bundle digest: %w", err)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

func hashBytes(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "checkpoint:", strings.TrimSpace(err.Error()))
	os.Exit(1)
}
